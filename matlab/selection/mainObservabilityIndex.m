% 功能说明：考察测量位姿数量变化对可观测性指标 O6 的影响。
% 当前读取第 3 个平面的数据；每次使用前 t 条样本拼接雅可比矩阵。
% 本脚本评估位姿集合的可观测性，不执行 DE 选择或机器人参数标定。
% 本次仅补充关键注释，保留原有计算语句、数据范围和绘图调用。

%% 1. 初始化与机器人名义参数
% 清空工作区并开始计时。
clear all
tic
%------------------------------------------
% 24 个名义参数的顺序：a1~a6、d1~d6、alpha1~alpha6、theta0_1~theta0_6。
% a、d 为长度参数；alpha 和 theta0 为角度参数，角度使用弧度。
a_d_alpha_theta0_norm0=...
    [0.24872627 0.90065082 -0.20466089 0 0 0 ...
    0.6535 0 0 1.03138548 0 0.2006 ...
    -1.571 0 1.571 -1.571 1.571 0 ...
    0 0 0 0 0 0]';%机器人的名义参数
a_d_alpha_theta0=a_d_alpha_theta0_norm0;
%------------------------------------------%------------------------------------------
% 数据读取
%% 2. 读取候选位姿数据，并将关节角从角度制转换为弧度制
% 工作表编号 3 对应第三个平面；A2:H200 共读取 199 条候选数据。
% A:F 为六个关节角，G 为拉线长度 L，H 为百分表读数 D。
% 【路径提示】原路径以反斜杠开头，指向当前盘符根目录，需确认文件位置。
script_dir=fileparts(mfilename('fullpath'));
data_file=fullfile(script_dir,'..','..','data','raw','HSR-P.xlsx');
data=readmatrix(data_file,'Sheet',3,'Range','A2:H200');
% data1 是重复读取的数据，后续当前脚本未使用，原语句予以保留。
data1=data;
% 雅可比函数中的三角函数使用弧度，因此六个关节角统一乘以 pi/180。
q1_batch = pi/180*data(:,1);
q2_batch = pi/180*data(:,2);
q3_batch = pi/180*data(:,3);
q4_batch = pi/180*data(:,4);
q5_batch = pi/180*data(:,5);
q6_batch = pi/180*data(:,6);
%------------------------------------------%------------------------------------------
%% 3. 初始化指标记录，以及拉线测量所需的固定点
% O1~O6 各自的记录数组；当前脚本只有 O6 被实际计算和写入。
o1_store1=zeros(0,1);
o2_store2=zeros(0,1);
o3_store3=zeros(0,1);
o4_store4=zeros(0,1);
o5_store5=zeros(0,1);
o6_store6=zeros(0,1);
% 将 G 列拉线长度由毫米换算为米；xyz 是地面固定点坐标，单位为米。
% 当前 O6 由雅可比奇异值确定，读取的 L_ex11 和下文 L1 不直接参与其计算。
L_ex11=1/1000*data(:,7);%拉线编码器拉线位移
xyz=[2.057225771615264 0.178849248296023 0.372330796755729]; %拉线编码器地面固定点
%------------------------------------------%------------------------------------------
%模型训练
%% 4. 逐步增加测量位姿数量，评估对应整组位姿的 O6
% 【关键】t 是选取的位姿数量，不是优化算法的训练迭代次数。
% 从 18 条开始，每次使用 data 的前 t 条样本，直到全部候选样本。
o1=0;
for t=18:length(q1_batch)
%------------------------------------------
% 每个 t 都重新构造扩展雅可比，避免混入上一个样本数量对应的矩阵。
J_store=[];
for i = 1:t %each i represent one measurement
    % 第 i 个样本的六维关节角列向量，单位为弧度。
    q=[q1_batch(i);q2_batch(i);q3_batch(i);q4_batch(i);q5_batch(i);q6_batch(i)]; 
    L1=[L_ex11(i)]; 
    % 用固定名义参数和固定点计算当前位姿的拉线长度误差雅可比。
    J_norm1=my_Jacobian(a_d_alpha_theta0,xyz,q);%误差雅可比矩阵
    % 【关键】沿用原程序的参数选择：仅取雅可比前 17 列。
    % 取 17 列并不自动保证列满秩，参数相关性会影响最小奇异值。
    J0=J_norm1(:,1:17);
    % 按行拼接各位姿雅可比，形成这 t 条测量对应的扩展矩阵。
    J_store=[J_store; J0];%拓展误差雅可比矩阵
end
    % 奇异值分解：J_store = u*s*v'；对角奇异值按从大到小排列。
    % s1 保存奇异值；s0 是其乘积，当前 O6 不使用 s0。
    [u,s,v]=svd(J_store);
    s1=diag(s);
    s0=prod(diag(s)); %奇异值分解
       
    % 【核心公式】O6 = sqrt(17) / sqrt(sum(1 ./ sigma_i.^2))。
    % 先累加 17 个奇异值倒数的平方，再进行归一化和开平方。
    % 接近零的奇异值会显著拉低 O6；奇异值为零时 O6 的极限为零。
    o6=0;%可观测性指标o6
    for b=1:17
    o6=o6+1/(s1(b))^2;
    end
    % O6 越大，表示该组位姿在本指标下越有利于参数辨识。
    o6=17^0.5*o6^-0.5;
    % 保存当前 t 对应的一个整组指标值，而不是第 t 条样本的单独分数。
    o6_store6=[o6_store6;o6];
end 
toc
%------------------------------------------
%数据可视化data visualization
% %------------------------------------------
%% 5. 绘制位姿数量与可观测性指标之间的关系
% 横坐标依次对应 18、19、...、N 条测量位姿，与 o6_store6 一一对应。
% 【原代码说明】O1~O5 未计算，其记录数组为空；下面相应绘图可能报维度不匹配。
% 如需查看 O1~O5，须先补充各自公式；这里仅添加注释，保留原绘图语句。
% semilogy 使用对数纵轴；当前绘制的是正 O6，和 DE 收敛图中的 -O6 不同。
t=18:length(q1_batch);
format long
% 下图是当前脚本实际计算出的 O6：横轴表示位姿数量。
% 原 xlabel 为 Iteration、ylabel 为 cond，但曲线实际不是迭代次数或条件数。
figure(6),clf(6),
semilogy(t,o6_store6)
xlabel('Iteration');
ylabel('cond');

